from abc import ABC, abstractmethod
from typing import AsyncIterator, Optional


class BaseEmbeddingProvider(ABC):
    """
    Abstract contract for text embedding generation.
    """
    @abstractmethod
    async def embed_text(self, text: str) -> list[float]:
        """
        Embeds a single string into a normalized vector.
        """
        pass

    @abstractmethod
    async def embed_batch(self, texts: list[str]) -> list[list[float]]:
        """
        Embeds multiple strings into normalized vectors in batches.
        """
        pass


class BaseLLMProvider(ABC):
    """
    Abstract contract for LLM generation and streaming.
    """
    @abstractmethod
    async def generate(
        self,
        prompt: str,
        system_prompt: Optional[str] = None,
        history: Optional[list[dict[str, str]]] = None,
    ) -> str:
        """
        Generates a complete response synchronously from the LLM.
        """
        pass

    @abstractmethod
    def generate_stream(
        self,
        prompt: str,
        system_prompt: Optional[str] = None,
        history: Optional[list[dict[str, str]]] = None,
    ) -> AsyncIterator[str]:
        """
        Yields tokens incrementally as they are generated by the LLM.
        """
        pass
